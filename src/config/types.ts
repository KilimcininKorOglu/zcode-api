/**
 * Configuration types for zcode-proxy.
 * @see .omo/plans/zcode-proxy.md Task 2
 */

/** Provider endpoint configuration (one per upstream provider). */
export interface ProviderEndpoints {
  /** Base URL for Anthropic-format API, e.g. "https://api.z.ai/api/anthropic". */
  anthropicBase: string;
  /** Base URL for OpenAI-format API, e.g. "https://api.z.ai/api/coding/paas/v4". */
  openaiBase: string;
}

/** Auth section of the proxy configuration. */
interface AuthConfig {
  /**
   * Key that clients must provide to use the proxy (via `Authorization: Bearer {proxyApiKey}`).
   * If unset, the proxy does not require client auth.
   */
  proxyApiKey?: string;
  /** Path to stored OAuth credentials created by `auth login`. */
  oauthCredentialsPath?: string;
}

/**
 * Identity headers injected on every upstream request to mimic the ZCode
 * desktop client. Mirrors the `pio` builder in the reverse-engineered bundle
 * (`_reverse/zcode.cjs`); see `_reverse/NOTEPAD.md` "How Credential is Used".
 *
 * Resolution: env var (matches ZCode's own convention) → YAML override → default.
 * `appVersion` must be printable ASCII (`/^[\x20-\x7e]+$/`); non-conforming
 * values are silently dropped and fall back to the default (current ZCode
 * release), exactly like `fio` in the bundle.
 */
export interface ProxyIdentity {
  appVersion: string;
  sourceTitle: string;
  refererOrigin: string;
  /**
   * Device identity for `X-Device-Mid` (mirrors ZCode's telemetry deviceMid:
   * a random UUIDv4 generated ONCE and reused forever — no hardware values).
   * Empty/undefined omits the header. Persisted in config.yaml
   * (`ensureDeviceMidInConfig`); the `ZCODE_IDENTITY_DEVICE_MID` env var wins
   * over YAML. Must stay stable per anti-pattern #13; never randomize
   * per-request.
   */
  deviceMid?: string;
}

/** Local client-session inference mode for upstream session affinity. */
export interface ClientIdentityConfig {
  /**
   * "enforce" (default) forwards a stable x-session-id for inferred sessions
   * (cache affinity; the official signing template always carries a session
   * id); "observe" logs only; "off" disables inference.
   */
  mode: "off" | "observe" | "enforce";
  /** In-memory session TTL in seconds. */
  ttlSeconds: number;
  /** Maximum number of inferred sessions retained in memory. */
  maxSessions: number;
}

/**
 * Responses-API (`/v1/responses`) configuration. When `enabled`, the proxy
 * translates Codex-style Responses requests to the GLM Chat Completions upstream.
 */
export interface ResponsesConfig {
  /** Enable the `/v1/responses` route. Default `true`. */
  enabled: boolean;
  /** Max stored responses (LRU). Default 1000. */
  storeMaxEntries: number;
  /** Stored-response TTL in ms. Default 24h (in-memory; cleared on restart). */
  storeTtlMs: number;
}

/**
 * Official plugin-MCP gateway (`/mcp` aggregate endpoint) — mirrors the ZCode
 * desktop's `zcode_official` MCP plane: every catalogue server is reached at
 * `{upstreamOrigin}/api/v1/mcp/server/{routeId}` with the stored OAuth
 * credential injected as official auth headers, and all tools are exposed
 * behind a single `/mcp` endpoint.
 *
 * The server table is a build-time artifact (`src/mcp/official-catalogue.json`,
 * regenerated by `scripts/regen-mcp-catalogue.ts`) — the runtime never fetches
 * the marketplace.
 */
export interface McpGatewayConfig {
  /** Expose the aggregated `/mcp` endpoint (POST JSON-RPC, GET listing, DELETE). Default `true`. */
  enabled: boolean;
  /** Base origin substituted for `${ZCODE_BASE_URL}` in plugin `.mcp.json`
   *  URLs. Default `https://zcode.z.ai` (desktop bundle production fallback
   *  `jee`; `sYe` = chatglm.site is the test-env origin). */
  upstreamOrigin: string;
}

/** GLM MCP hosted-tool configuration. Endpoints are derived from the active provider. */
export interface McpConfig {
  /** Enable MCP interception (web_search) and function-tool injection (web_reader/zread). Default `true`. */
  enabled: boolean;
  /** Intercept `web_search` / `web_search_preview` hosted tools via GLM `web_search_prime` MCP. Default `true`. */
  webSearch: boolean;
  /** Inject `webReader` as a function tool the model can call. Default `false` (off by default to limit scope). */
  webReader: boolean;
  /** Inject the three `zread` tools as function tools. Default `false`. */
  zread: boolean;
  /** Official plugin-MCP gateway (`/mcp` aggregate). Separate plane from the
   *  GLM hosted-tool fields above (those remain unwired). */
  gateway: McpGatewayConfig;
}

/**
 * Async (off-peak / idle-plan) bridge configuration. When `enabled`, exposes
 * `/async/v1/messages` and `/async/v1/chat/completions` that route to ZCode's
 * off-peak ticket-queue backend. The proxy keeps the client connection alive
 * with SSE comments during ticket-queue wait, forwards the LLM stream once
 * the ticket is `ready`, and auto-retries on ticket-expired (up to `maxRetries`).
 *
 * Requires a logged-in oauth credential (off-peak needs both
 * `Authorization: Bearer ${jwt}` and `X-Coding-Plan-Api-Key` headers). A
 * credential lacking the JWT makes the route entry return 400
 * `async_credentials_unavailable`.
 *
 * @see _reverse/NOTEPAD.md "Off-Peak / Idle Plan" section for full upstream protocol.
 */
export interface AsyncConfig {
  /** Enable the `/async/*` routes. Default `false`. */
  enabled: boolean;
  /** Base origin for off-peak endpoints. Default `"https://zcode.z.ai"`. */
  origin: string;
  /** Ticket-status poll interval in ms. Default `5000`. */
  pollIntervalMs: number;
  /** SSE keepalive comment interval during ticket-queue wait, in ms. Default `3000`. */
  keepAliveIntervalMs: number;
  /** Maximum total wait time for a ticket to become `ready`, in ms. `0` = unlimited. Default `0`. */
  maxWaitMs: number;
  /** Maximum auto-retry count on `off-peak-ticket-expired`. Default `3`. */
  maxRetries: number;
  /** Settle call timeout in ms (best-effort close-out on completion/abort). Default `8000`. */
  settleTimeoutMs: number;
  /** Control-plane call (takeTicket/pollStatus) timeout in ms. Default `15000`. */
  controlTimeoutMs: number;
  /** Optional model override; empty string uses the request's `model`. Default `""`. */
  defaultModel: string;
}

/**
 * Manual claim ("weekend plan") — mirrors the ZCode 3.10 desktop client's
 * `manualClaimPlan` feature: periodically list claimable trial plans
 * (`GET {origin}/api/v1/zcode-plan/billing/preview`) and, when one is
 * available, claim it (`POST {origin}/api/v1/zcode-plan/billing/claim`) with
 * the OAuth JWT and an Aliyun captcha token. Claimed plans grant Start-Plan
 * style quota with delayed activation (`effective_at` / `starts_at`).
 *
 * Requires `auth.mode: oauth` (claim uses `Authorization: Bearer ${jwt}`).
 *
 * @see _reverse/NOTEPAD.md "Manual Claim Plan" section for the protocol.
 */
export interface ClaimConfig {
  /** Enable the claim subsystem (CLI `claim` command + auto scheduler). Default `true`. */
  enabled: boolean;
  /** Auto-claim in the background while the proxy is serving. Default `true` (effective when `enabled`). */
  auto: boolean;
  /** Base origin of the zcode-plan billing endpoints. Default `"https://zcode.z.ai"`. */
  origin: string;
  /** Preview poll interval in seconds. Default `300` (5 min). */
  pollIntervalSec: number;
  /** Backoff after a failed claim attempt in ms. Default `600000` (10 min). */
  cooldownMs: number;
  /** Optional `plan_id` to claim; empty string claims the highest-priority preview. Default `""`. */
  planId: string;
}

/**
 * Provider endpoint routing — mirrors the ZCode client's
 * `ProviderEndpointRoutingService`: periodically fetch
 * `GET {configUrl}/api/v1/agent/configs` and rewrite matching upstream URLs
 * per the server-controlled `data.proxyEndpoint.mapping` table. As of
 * 2026-08-19 only the coding-plan Anthropic endpoints are mapped (to
 * `zcode.z.ai/api/v1/ultra[-zai]/...`); resolution is generic so future
 * entries apply automatically. Always fail-open.
 */
export interface EndpointRoutingConfig {
  /** Enable URL remapping. Default `true`. */
  enabled: boolean;
  /** Base origin of the agent-configs endpoint. Default `"https://zcode.z.ai"`. */
  origin: string;
}

/**
 * Client request signing V4 — mirrors the ZCode 3.15.1
 * `requiresClientRequestSigning` static rule (bundle `TUs`): coding-plan
 * credentials are always signed (handshake + Ed25519 + proof-of-work, with
 * the client's fail-open retry ladder); start-plan, off-peak and highspeed
 * paths are never signed. The 3.12.3–3.14.4 `agent/configs`
 * `codingPlanSignature` gate probe no longer exists on either side.
 */
export interface ClientSigningConfig {
  /** Enable signing. Default `true`. */
  enabled: boolean;
}

/**
 * HighSpeed card manager (ZCode 3.15.1 HighspeedCardService mirror).
 * When coding-plan requests arrive, draws are lazily triggered
 * (`POST {origin}/api/v1/highspeed/draw`). Eligible requests within the card
 * window (server expires_at, baseline ~5min) share the card: the model is
 * rewritten to the card's model, auth is replaced with the JWT + card-id set,
 * and requests remain unsigned (official static rule). task_id reuses
 * client-session affinity inference. When accounts are not in the rollout
 * (503 / biz 3404), a 10min negative cache prevents repeated latency spikes.
 */
export interface HighspeedConfig {
  /** Enable the highspeed card worker. Default `true` (the official client has no toggle at all). */
  enabled: boolean;
  /** Base origin of the highspeed gateway. Default `"https://zcode.z.ai"`. */
  origin: string;
  /** Eligible model prefixes that trigger draws / accept cards. Default `["glm-5.3", "glm-5.2", "glm-5.1"]`. */
  models: string[];
}

/** Upstream plan tiers the routing and auto-switch move between. */
export type PlanTier = "coding-plan" | "start-plan";

/** Preference order used when the config carries none (today's behavior). */
export const DEFAULT_PLAN_PRIORITY: PlanTier[] = ["start-plan", "coding-plan"];

/** Default poll cadence for the plan auto-switch watcher, in seconds. */
export const DEFAULT_PLAN_POLL_INTERVAL_SEC = 30;

/**
 * Per-plan exhaustion rule: the upstream signals that make the plan "not
 * enough" so the next plan in `planPriority` takes over. coding-plan rows are
 * monitor-plane limit types (TOKENS_LIMIT = the 5h window, TIME_LIMIT = the
 * monthly period, WEEK_LIMIT = the weekly window, not yet reported upstream);
 * start-plan has the single BALANCE signal (the trial credits plane).
 */
export interface PlanSwitchRule {
  limits: string[];
}

/** Default rules: every known signal of each plan is watched. */
export const DEFAULT_PLAN_SWITCH_RULES: { "coding-plan": PlanSwitchRule; "start-plan": PlanSwitchRule } = {
  "coding-plan": { limits: ["TOKENS_LIMIT", "TIME_LIMIT", "WEEK_LIMIT"] },
  "start-plan": { limits: ["BALANCE"] },
};

/**
 * Automatic consumption of the upstream 5h-window reset rights (the ZCode
 * "🎁 N reset available" badges). The server grants rights on its own
 * judgment; the proxy only READS them (`GET /api/v1/coding-plan/reset/status`)
 * and spends them (`POST .../reset/use`) when one of the user-configured
 * triggers holds. Default on.
 */
export interface PlanAutoResetConfig {
  /** Master switch; off = rights are never read and never spent. Default true. */
  enabled: boolean;
  /** Spend a right when the 5h window's used share reaches this percent. Default 90. */
  useThresholdPercent: number;
  /** Spend a right right after a coding-plan 429 and retry the request. Default true. */
  useOn429: boolean;
  /** Spend a right when its remaining lifetime drops below this many seconds. Default 600. */
  expireGraceSec: number;
  /** Reset-status poll cadence in seconds (the official client polls every 300s). Default 300. */
  statusPollIntervalSec: number;
}

/** Shipped defaults for {@link PlanAutoResetConfig}. */
export const DEFAULT_PLAN_AUTO_RESET: PlanAutoResetConfig = {
  enabled: true,
  useThresholdPercent: 90,
  useOn429: true,
  expireGraceSec: 600,
  statusPollIntervalSec: 300,
};

/**
 * Marketing & Touch auto-claimer: periodically polls
 * `GET {origin}/api/v1/marketing/touch` for targeted campaigns/promotions/gifts
 * and automatically acknowledges / claims them via
 * `POST {origin}/api/v1/marketing/touch/action` with `action_type: "confirm"`.
 */
export interface MarketingConfig {
  /** Enable the marketing campaign auto-claimer. Default `true`. */
  enabled: boolean;
  /** Base origin of the marketing touch endpoints. Default `"https://zcode.z.ai"`. */
  origin: string;
  /** Check interval in seconds. Default `1800` (30 minutes). */
  intervalSec: number;
}

/** Shipped defaults for {@link MarketingConfig}. */
export const DEFAULT_MARKETING_CONFIG: MarketingConfig = {
  enabled: true,
  origin: "https://zcode.z.ai",
  intervalSec: 1800,
};

/** Top-level proxy configuration. */
export interface ProxyConfig {
  server: {
    port: number;
    host: string;
  };
  auth: AuthConfig;
  /** Active upstream provider. */
  provider: "zai" | "bigmodel";
  /** Which plan tier to use. "coding-plan" (default) uses direct upstream endpoints; "start-plan" routes through zcode.z.ai with JWT auth. */
  plan: PlanTier;
  /**
   * Plan preference order for the auto-switch: the first plan whose watched
   * signals still have quota serves every request while `planAutoSwitch` is
   * on. Default ["start-plan", "coding-plan"] (prefer the trial). A rejected
   * request still falls over for that one request (see the plan fallback),
   * flag on or off. `loadConfig` always sets this; fixtures may omit it.
   */
  planPriority?: PlanTier[];
  /**
   * Hybrid plan auto-switch master switch: on = the watcher keeps the
   * effective plan on the first usable entry of `planPriority` and a
   * rejected request falls to the next plan for that one request; off =
   * `plan` above is used exactly as configured, with no fallback at all.
   * `loadConfig` always sets this; fixtures may omit it.
   */
  planAutoSwitch?: boolean;
  /**
   * Which signals make each plan "not enough" for the auto-switch watcher.
   * Default: every known signal (coding-plan TOKENS_LIMIT + TIME_LIMIT +
   * WEEK_LIMIT, start-plan BALANCE). `loadConfig` always sets this; fixtures
   * may omit it.
   */
  planSwitchRules?: { "coding-plan": PlanSwitchRule; "start-plan": PlanSwitchRule };
  /** Auto-switch poll interval in seconds (default 30; watcher restarts on change). */
  planPollIntervalSec?: number;
  /**
   * Automatic use of the upstream 5h-window reset rights. Default on with
   * threshold 90% / grace 10min / status poll 5min; `loadConfig` always sets
   * this; fixtures may omit it (accessors in src/plan/reset.ts fail open to
   * the defaults).
   */
  planAutoReset?: PlanAutoResetConfig;
  /**
   * Send batch (non-streaming) client requests upstream as `stream: true` and
   * reassemble the SSE into the single JSON the client expects. The upstream
   * gateway kills requests whose time-to-first-byte sits silent past ~180s,
   * which only non-streaming generations can hit; streaming starts delivering
   * bytes immediately. Default true; `loadConfig` always sets it; fixtures may
   * omit it.
   */
  batchAsStream?: boolean;
  /** Per-provider endpoint overrides. */
  providers: {
    zai: ProviderEndpoints;
    bigmodel: ProviderEndpoints;
  };
  /** Default model id used when client request omits `model`. */
  defaultModel: string;
  /** Whitelist of allowed model ids. */
  models: string[];
  /**
   * Identity headers injected upstream. Always present after `loadConfig`;
   * defaults mirror the production ZCode desktop client.
   */
  identity: ProxyIdentity;
  /** Local client session inference for cache-affinity experiments. */
  clientIdentity: ClientIdentityConfig;
  /** Responses-API (`/v1/responses`) configuration. */
  responses: ResponsesConfig;
  /** Server-controlled upstream URL remapping (ultra endpoints). */
  endpointRouting: EndpointRoutingConfig;
  /** Client request signing V4 (Ed25519 + PoW, static coding-plan rule). */
  clientSigning: ClientSigningConfig;
  /** HighSpeed card worker (enabled by default — the official client has no toggle). */
  highspeed: HighspeedConfig;
  /** GLM MCP hosted-tool configuration. */
  mcp: McpConfig;
  /** Async (off-peak / idle-plan) bridge configuration. */
  async: AsyncConfig;
  /** Manual claim ("weekend plan") configuration. */
  claim: ClaimConfig;
  /** Marketing & Touch promotional campaign auto-claimer. */
  marketing?: MarketingConfig;
  logging: {
    level: "debug" | "info" | "warn" | "error";
  };
}
